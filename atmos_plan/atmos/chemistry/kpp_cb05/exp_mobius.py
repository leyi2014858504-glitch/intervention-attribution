"""n=8 Moebius interaction spectrum over emission-switch players  (PILOT).

PLAYERS (pre-registered)
  index 0..3 : NOx emission OFF in window 1..4   (windows of 6 h:
               [00-06) [06-12) [12-18) [18-24), repeating every day)
  index 4..7 : anthropogenic-VOC emission OFF in window 1..4
  Biogenic isoprene is NOT an intervention (it stays on).
  Intervention semantics: BINARY switch, that sector's emission -> 0 in that
  window.  Nothing changes outside the window; the switch repeats on each of
  the three days of the episode.

VALUE FUNCTION
  v(S) = mean O3 over the LAST 24 h of a 72 h episode, minus the same metric at
         S = {} (so v({}) = 0).  The first 48 h are spin-up and are discarded.
  Units: ppb, box mean.

MOEBIUS TRANSFORM
  m(A) = sum_{B subset A} (-1)^(|A|-|B|) v(B)
  m({}) = 0 ;  m({i}) = main effect of i ;  m({i,j}) = 2-way interaction, etc.
  This is exactly the Stein-Alpert Factor Separation decomposition generalised
  to n players.

PRE-REGISTERED RULES (fixed before the run; no post-hoc adjustment)
  R_k   := max_{|A|=k} |m(A)| / max_i |m({i})|          (order-k spectral level)
  rho   := mean|m| over the 24 cross-window 2-way terms /
           mean|m| over the  4 within-window 2-way terms

  SANITY  : max_i |m({i})| >= 0.5 ppb, else the scenario is too insensitive to
            say anything (verdict INVALID).
  PASS    : R_2 < 0.20  AND  R_3 < 0.20  AND  rho < 1.0
            (2nd/3rd order interactions subdominant, interactions time-local)
  STOP    : R_2 > 0.50
            (spectrum essentially dense at 2nd order -> the sparse-spectrum +
             guided-enumeration route is dead)
  else    : INCONCLUSIVE

  Reference for "how dense could it have been": a NULL model in which the 255
  non-empty v values are randomly permuted among the 255 non-empty subsets
  (fixed seed).  Its R_k is reported alongside; a genuinely sparse spectrum
  must sit far below it.

All 256 configurations are run in ONE WSL batch (see sweep_mobius.sh), not one
wsl.exe call per run.

Usage: python exp_mobius.py [backend] [--probe]
Outputs: mobius_results_<backend>.txt, mobius_spectrum_<backend>.csv
"""
import csv
import itertools
import os
import random
import subprocess
import sys
import time

from kpp_box import BACKENDS, nml_text, run_scenario

BACKEND = sys.argv[1] if len(sys.argv) > 1 else "dummy"
PROBE = "--probe" in sys.argv
HERE = os.path.dirname(os.path.abspath(__file__))
W = "/mnt/d/atmos/_kppwork"

NPLAY = 8
MAX1 = 1 << NPLAY
SEED = 20260912
R2_PASS, R3_PASS, RHO_PASS, R2_STOP, SANITY = 0.20, 0.20, 1.0, 0.50, 0.5

SWEEP = """#!/bin/bash
# generated by exp_mobius.py: run every subset nml once, collect the metric
set -u
D={d}
N={n}
O={o}
echo "name,v_ppb,nfail,rc,nrow" > $O
for f in $N/mob_*.nml; do
  b=$(basename $f .nml)
  cp $f $D/cb05.nml
  cd $D
  rm -f traj.dat state_out.dat run.log
  timeout 300 ./cb05.exe > run.log 2>&1
  rc=$?
  nf=$(grep -o 'NFAIL=[ ]*[0-9]*' run.log | tr -dc '0-9')
  nrow=$(awk 'END{{print NR-1}}' traj.dat 2>/dev/null)
  v=$(awk 'NR>1 && $1>=48 {{s+=$2; n++}} END {{if(n>0) printf "%.6f", s/n; else printf "NaN"}}' traj.dat 2>/dev/null)
  echo "$b,${{v:-NaN}},${{nf:-NA}},$rc,${{nrow:-0}}" >> $O
done
echo SWEEP_DONE >> $O
"""


def pc(m):
    return bin(m).count("1")


def name_of(mask):
    parts = ["%s@W%d" % ("NOx" if i < 4 else "VOC", (i % 4) + 1)
             for i in range(NPLAY) if mask & (1 << i)]
    return "+".join(parts) if parts else "base"


def cfg_of(mask):
    """namelist overrides for a subset mask (bit set = that emission switched OFF)."""
    return {"NOXW": [0.0 if (mask >> w) & 1 else 1.0 for w in range(4)],
            "VOCW": [0.0 if (mask >> (4 + w)) & 1 else 1.0 for w in range(4)]}


def sweep(masks):
    """Run all masks in one WSL batch; return {mask: v_ppb}."""
    nd = os.path.join(HERE, "nmldir")
    os.makedirs(nd, exist_ok=True)
    for mask in masks:
        with open(os.path.join(nd, "mob_%03d.nml" % mask), "w", newline="\n") as f:
            f.write(nml_text(cfg_of(mask), BACKEND))
    body = os.path.join(HERE, "sweep_mobius.sh")
    body_wsl = W + "/sweep_mobius.sh"
    outcsv = "%s/mobius_v_%s.csv" % (W, BACKEND)
    with open(body, "w", newline="\n") as f:
        f.write(SWEEP.format(d=BACKENDS[BACKEND], n=W + "/nmldir", o=outcsv))
    r = subprocess.run(["wsl.exe", "bash", "-lc",
                        "dos2unix -q %s; bash %s" % (body_wsl, body_wsl)],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError("sweep failed rc=%d: %s" % (r.returncode, r.stderr[-400:]))
    out = {}
    with open(os.path.join(HERE, "mobius_v_%s.csv" % BACKEND)) as f:
        for row in csv.DictReader(f):
            if "SWEEP_DONE" in str(row.get("name", "")):
                continue
            if row.get("v_ppb", "NaN") == "NaN":
                raise RuntimeError("subset %s produced no metric (%s)" % (row, ""))
            assert int(row["nfail"]) == 0 and int(row["rc"]) == 0, row
            assert int(row["nrow"]) > 200, row
            out[int(row["name"].split("_")[1])] = float(row["v_ppb"])
    assert len(out) == len(masks), "got %d of %d subsets" % (len(out), len(masks))
    return out


def mobius(v):
    """m[mask] = sum_{sub subset mask} (-1)^(pc(mask)-pc(sub)) v[sub]."""
    out = [0.0] * MAX1
    for mask in range(MAX1):
        s, sub = 0.0, mask
        while True:
            s += (1.0 if ((pc(mask) - pc(sub)) % 2 == 0) else -1.0) * v[sub]
            if sub == 0:
                break
            sub = (sub - 1) & mask
        out[mask] = s
    return out


def levels(m):
    byk = {}
    for mask in range(1, MAX1):
        byk.setdefault(pc(mask), []).append(abs(m[mask]))
    return {k: max(xs) for k, xs in byk.items()}


def main():
    t0 = time.time()

    if PROBE:
        for mask in (0, 1 << 2, 1 << 6):
            m = run_scenario(cfg_of(mask), "mob_%03d" % mask, BACKEND)
            print("%-22s d3_mean=%.4f  nfail=%d" % (name_of(mask), m["d3_mean"], m["nfail"]),
                  flush=True)
        return

    masks = list(range(MAX1))
    if "--analyze" in sys.argv:
        v_abs = {}
        with open(os.path.join(HERE, "mobius_v_%s.csv" % BACKEND)) as f:
            for row in csv.DictReader(f):
                if "SWEEP_DONE" in str(row.get("name", "")):
                    continue
                v_abs[int(row["name"].split("_")[1])] = float(row["v_ppb"])
        assert len(v_abs) == len(masks), "only %d of %d subsets swept" % (len(v_abs), len(masks))
        print("reusing sweep: %d subsets" % len(v_abs), flush=True)
    else:
        v_abs = sweep(masks)
        print("sweep done: %d subsets in %.0fs" % (len(masks), time.time() - t0), flush=True)

    base = v_abs[0]
    vv = [v_abs[i] - base for i in range(MAX1)]        # v({}) = 0
    m = mobius(vv)

    # self-check: the zeta transform of m must give v back exactly
    err = 0.0
    for mask in range(MAX1):
        s, sub = 0.0, mask
        while True:
            s += m[sub]
            if sub == 0:
                break
            sub = (sub - 1) & mask
        err = max(err, abs(s - vv[mask]))
    assert err < 1e-9, "Moebius round-trip error %.3e" % err

    L = ["n=8 Moebius interaction spectrum (PILOT), backend=%s, sweep=%.0fs"
         % (BACKEND, time.time() - t0), ""]
    L.append("baseline metric (mean O3, last 24 h) = %.4f ppb" % base)
    L.append("Moebius round-trip check (zeta(m) == v): max error %.2e" % err)
    L.append("")
    L.append("main effects m({i})  [ppb]:")
    for i in range(NPLAY):
        L.append("  %-9s %+8.4f" % (name_of(1 << i), m[1 << i]))
    max1 = max(abs(m[1 << i]) for i in range(NPLAY))

    lv = levels(m)
    L.append("")
    L.append("order-k spectral level   R_k = max|m| / max|main|:")
    for k in sorted(lv):
        L.append("  |A|=%d   max|m|=%10.4f   R_%d = %.4f" % (k, lv[k], k, lv[k] / max1))

    win, cross = [], []
    for a, b in itertools.combinations(range(NPLAY), 2):
        (win if abs(a - b) == 4 else cross).append(abs(m[(1 << a) | (1 << b)]))
    rho = (sum(cross) / len(cross)) / (sum(win) / len(win))
    L.append("")
    L.append("2-way terms: within-window (n=%d) vs cross-window (n=%d)"
             % (len(win), len(cross)))
    L.append("  within : max=%8.4f mean=%8.4f   values %s"
             % (max(win), sum(win) / len(win),
                " ".join("%+.3f" % m[(1 << w) | (1 << (4 + w))] for w in range(4))))
    L.append("  cross  : max=%8.4f mean=%8.4f" % (max(cross), sum(cross) / len(cross)))
    L.append("  rho = mean|cross| / mean|within| = %.4f" % rho)

    rng = random.Random(SEED)
    perm = list(range(1, MAX1))
    rng.shuffle(perm)
    vn = [0.0] * MAX1
    for i, src in enumerate(range(1, MAX1)):
        vn[perm[i]] = vv[src]
    mn = mobius(vn)
    lvn = levels(mn)
    max1n = max(abs(mn[1 << i]) for i in range(NPLAY))
    nullR2 = lvn[2] / max1n
    nullR3 = lvn[3] / max1n
    L.append("")
    L.append("NULL model (random permutation of the 255 values, seed=%d):" % SEED)
    for k in sorted(lvn):
        L.append("  |A|=%d   R_%d = %.4f" % (k, k, lvn[k] / max1n))

    ncoef = sum(1 for mask in range(1, MAX1) if pc(mask) >= 2)
    nsig = sum(1 for mask in range(1, MAX1)
               if pc(mask) >= 2 and abs(m[mask]) > 0.05 * max1)
    L.append("")
    L.append("high-order coefficients (|A|>=2): %d total, %d above 5%% of max|main|"
             % (ncoef, nsig))
    # distribution of the 2-way terms: is R_2 driven by one outlier or by many?
    two = sorted((abs(m[(1 << a) | (1 << b)]) for a, b in
                  itertools.combinations(range(NPLAY), 2)), reverse=True)
    L.append("2-way coefficient distribution (n=%d), as fraction of max|main|=%.2f ppb:"
             % (len(two), max1))
    for thr in (0.5, 0.2, 0.1, 0.05, 0.01):
        L.append("  |m| > %5.1f%% of max|main| : %2d" % (100 * thr, sum(1 for x in two if x > thr * max1)))
    L.append("  median |m| = %.4f ppb (%.3f of max|main|)"
             % (two[len(two) // 2], two[len(two) // 2] / max1))
    L.append("largest 2-way terms:")
    tw = sorted(((abs(m[(1 << a) | (1 << b)]), a, b)
                 for a, b in itertools.combinations(range(NPLAY), 2)), reverse=True)
    for val, a, b in tw[:6]:
        L.append("  %-24s %+8.4f" % (name_of((1 << a) | (1 << b)), m[(1 << a) | (1 << b)]))

    R2, R3 = lv[2] / max1, lv[3] / max1
    L.append("")
    L.append("DECISION (pre-registered)")
    L.append("  sanity  max|main| = %.4f ppb  (need >= %.1f)" % (max1, SANITY))
    L.append("  R_2 = %.4f  (PASS < %.2f, STOP > %.2f)    null R_2 = %.4f"
             % (R2, R2_PASS, R2_STOP, nullR2))
    L.append("  R_3 = %.4f  (PASS < %.2f)                 null R_3 = %.4f"
             % (R3, R3_PASS, nullR3))
    L.append("  rho = %.4f  (PASS < %.2f)" % (rho, RHO_PASS))
    if max1 < SANITY:
        verdict = "INVALID (scenario too insensitive)"
    elif R2 > R2_STOP:
        verdict = "STOP (spectrum dense at 2nd order)"
    elif R2 < R2_PASS and R3 < R3_PASS and rho < RHO_PASS:
        verdict = "PASS (pilot supports the sparse-spectrum hypothesis)"
    else:
        verdict = "INCONCLUSIVE"
    L.append("  VERDICT: %s" % verdict)

    txt = "\n".join(L)
    print("\n" + txt)
    with open(os.path.join(HERE, "mobius_results_%s.txt" % BACKEND), "w") as f:
        f.write(txt + "\n")
    with open(os.path.join(HERE, "mobius_spectrum_%s.csv" % BACKEND), "w",
              newline="") as f:
        w = csv.writer(f)
        w.writerow(["mask", "order", "set", "v_ppb", "m_ppb"])
        for mask in range(MAX1):
            w.writerow([mask, pc(mask), name_of(mask), "%.6f" % vv[mask], "%.6f" % m[mask]])


if __name__ == "__main__":
    main()
