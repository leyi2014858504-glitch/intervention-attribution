"""Generate the scenario-forcing ("dummy reaction") block for the CB05 box.

Why: the G4 scenario driver used operator splitting
    C += dt * (E(t) - k(t)*(C - Cbg))
outside the integrator.  For Moebius interaction spectroscopy that is wrong:
the inter-step coupling introduced by the splitting would be mixed into the
interaction spectrum together with genuine chemical non-linearity, and the
source/sink terms never enter the stoichiometric matrix, so the G3 atom
accounting cannot be closed.

Here the same physics is written as ordinary reactions:

    < Rn> FSRC = X          : EMIS_X(TEMP);   anthropogenic/biogenic emission
    < Rn> X    = FSNK       : KDILK(TEMP);    ventilation of every VAR species
    < Rn> FBCK = X          : BGIN_X(TEMP);   inflow toward the background

FSRC, FBCK and FSNK are FIXED species held at exactly 1 molecule/cm3 by the
driver, so a reaction "FSRC = X : R" injects exactly R molecules/cm3/s, and
"X = FSNK : k" removes X at exactly k*[X].

Emission and background inflow use DIFFERENT pools (FSRC vs FBCK) on purpose:
with a shared pool the two would be stoichiometrically identical and KPP would
merge them as duplicate equations, which would destroy the separation an
intervention needs (it must switch off the emission without touching the
background inflow).

The script is idempotent: everything it writes lives between marker comments.
Run it from this directory:  python mk_dummy.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SPC = os.path.join(HERE, "cb05_sorg_aq.spc")
EQN = os.path.join(HERE, "cb05_sorg_aq.eqn")
DEF = os.path.join(HERE, "cb05_sorg_aq.def")

# species that receive an emission (the intervention-relevant sources)
EMIS = ["no", "no2", "co", "par", "tol", "xyl", "pna", "isop"]
# species with a non-zero background (dilution inflow)
BGIN = ["o3", "no2", "no", "co", "par", "tol", "xyl", "isop"]

MARK_BEG = "//--- BEGIN DUMMY FORCING (generated by mk_dummy.py) ---"
MARK_END = "//--- END DUMMY FORCING ---"


def read(p):
    with open(p, newline="") as f:
        return f.read().replace("\r\n", "\n")


def write(p, s):
    with open(p, "w", newline="\n") as f:
        f.write(s)


def var_species():
    """DEFVAR species of cb05_sorg_aq.spc, in file order (= KPP VAR order)."""
    txt = read(SPC)
    m = re.search(r"#DEFVAR(.*?)#DEFFIX", txt, re.S)
    if not m:
        sys.exit("no #DEFVAR..#DEFFIX block found in %s" % SPC)
    names = re.findall(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=", m.group(1), re.M)
    if len(names) != 97:
        sys.exit("expected 97 DEFVAR species, found %d" % len(names))
    return names


def patch_spc():
    txt = read(SPC)
    if "FSRC" in txt:
        return
    if not txt.rstrip().endswith(";"):
        sys.exit("unexpected #DEFFIX tail in %s" % SPC)
    txt = txt.rstrip("\n") + (
        "\n FSRC = IGNORE ;   {scenario forcing: emission source pool, held at 1 molec/cm3}\n"
        " FBCK = IGNORE ;   {scenario forcing: background inflow pool, held at 1 molec/cm3}\n"
        " FSNK = IGNORE ;   {scenario forcing: ventilation sink pool, held at 1 molec/cm3}\n"
    )
    write(SPC, txt)


def eqn_block(var):
    L = []
    L.append(MARK_BEG)
    L.append("// NOTE: these are not chemistry.  See mk_dummy.py for the rationale.")
    L.append("// FSRC / FSNK are fixed species held at 1 molec/cm3 by the driver.")
    L.append("")
    L.append("// -- emissions (switchable: the intervention variables) --")
    n = 192
    for s in EMIS:
        L.append("<R%d>  FSRC                   = %-8s               : SRC_%s(TEMP);"
                 % (n, s.upper(), s.upper()))
        n += 1
    L.append("")
    L.append("// -- ventilation (first-order loss, every variable species) --")
    for s in var:
        L.append("<R%d>  %-8s               = FSNK                   : KDILK(TEMP);"
                 % (n, s.upper()))
        n += 1
    L.append("")
    L.append("// -- inflow toward the background --")
    for s in BGIN:
        L.append("<R%d>  FBCK                   = %-8s               : BGIN_%s(TEMP);"
                 % (n, s.upper(), s.upper()))
        n += 1
    L.append(MARK_END)
    return "\n".join(L) + "\n", 192, n - 1


def patch_eqn():
    txt = read(EQN)
    block, first, last = eqn_block(var_species())
    if MARK_BEG in txt:
        i = txt.index(MARK_BEG)
        j = txt.index(MARK_END) + len(MARK_END) + 1
        txt = txt[:i] + block + txt[j:]
    else:
        txt = txt.rstrip("\n") + "\n\n" + block
    write(EQN, txt)
    return first, last


GLOBALS = """
! ---------------------------------------------------------------------------
! Scenario forcing (see mk_dummy.py).  The driver refreshes these once per
! outer step, BEFORE Update_SUN/Update_RCONST.
!   E_*    : emission rates                     [molecules/cm3/s]
!   CBG_*  : background concentrations           [molecules/cm3]
!   K_DIL  : ventilation (dilution) rate         [1/s]
! The matching dummy reactions read them through the rate laws SRC_*/BGIN_*/
! KDILK, so the forcing enters the ODE right-hand side and the stoichiometric
! matrix exactly like a reaction.  (The globals are prefixed CBG_/SRC_ rather
! than BG_/EMIS_ so that they cannot collide with the driver's namelist
! variables BG_O3/BG_VOC/EMIS_CO, which are shared with the splitting build.)
! ---------------------------------------------------------------------------
REAL(KIND=dp) :: E_NO, E_NO2, E_CO, E_PAR, E_TOL, E_XYL, E_PNA, E_ISOP
REAL(KIND=dp) :: CBG_O3, CBG_NO2, CBG_NO, CBG_CO, CBG_PAR, CBG_TOL, CBG_XYL, CBG_ISOP
REAL(KIND=dp) :: K_DIL
"""


def rates_block():
    L = ["! ---------------------------------------------------------------------------",
         "! Scenario-forcing rate laws.  Each is a plain function of the forcing",
         "! globals so KPP treats the dummy reactions as concentration-independent",
         "! sources (or, for KDILK, first order in the reacting species).",
         "! ---------------------------------------------------------------------------"]
    for s in EMIS:
        u = s.upper()
        L += ["REAL(KIND=dp) FUNCTION SRC_%s(TEMP)" % u,
              "  REAL(KIND=dp), INTENT(IN) :: TEMP",
              "  SRC_%s = E_%s" % (u, u),
              "END FUNCTION SRC_%s" % u]
    for s in BGIN:
        u = s.upper()
        L += ["REAL(KIND=dp) FUNCTION BGIN_%s(TEMP)" % u,
              "  REAL(KIND=dp), INTENT(IN) :: TEMP",
              "  BGIN_%s = K_DIL*CBG_%s" % (u, u),
              "END FUNCTION BGIN_%s" % u]
    L += ["REAL(KIND=dp) FUNCTION KDILK(TEMP)",
          "  REAL(KIND=dp), INTENT(IN) :: TEMP",
          "  KDILK = K_DIL",
          "END FUNCTION KDILK"]
    return "\n".join(L)


def patch_def():
    txt = read(DEF)

    # --- F90_GLOBAL: append our declarations just before its #ENDINLINE
    m = re.search(r"#INLINE F90_GLOBAL(.*?)#ENDINLINE", txt, re.S)
    if not m:
        sys.exit("no F90_GLOBAL block in %s" % DEF)
    body = m.group(1)
    if "E_NO" not in body:
        body = body.rstrip("\n") + "\n" + GLOBALS.rstrip("\n") + "\n"
        txt = txt[:m.start(1)] + body + txt[m.end(1):]

    # --- F90_RATES: append our rate laws just before its #ENDINLINE
    m = re.search(r"#INLINE F90_RATES(.*?)#ENDINLINE", txt, re.S)
    if not m:
        sys.exit("no F90_RATES block in %s" % DEF)
    body = m.group(1)
    if "FUNCTION SRC_NO" not in body:
        body = body.rstrip("\n") + "\n\n" + rates_block() + "\n"
        txt = txt[:m.start(1)] + body + txt[m.end(1):]

    write(DEF, txt)


def main():
    patch_spc()
    first, last = patch_eqn()
    patch_def()
    print("OK: dummy reactions R%d..R%d appended" % (first, last))
    n_react = 191 + len(EMIS) + 97 + len(BGIN)
    print("    emission=%d  ventilation=97  background=%d  -> NREACT=%d"
          % (len(EMIS), len(BGIN), n_react))


if __name__ == "__main__":
    main()
